/* TRACK CODES AND THE GENERATOR, RETENTION.md "Measure" 4, in Node (the
   generator is deterministic across engines, see tracks/dmath.js).

   node game/test/retention/codes.js [--quick]

   1. Round trips: 1,000 random settings and seeds encode to a code that
      decodes to the same settings and seed, and the track generated from
      the decoded spec has the same centre line hash as the one from the
      original. Known answer: one character of a code changed is either
      rejected or decodes to a different seed or settings (never the same
      track).
   2. Malformed codes: a fuzzed set (wrong lengths, characters outside
      the alphabet, random strings of the right length, every single
      character substitution of a valid code, a crossover on a track that
      cannot have one) is rejected with a reason, and decode never throws.
   3. The default generator is unchanged: 400 seeds generated by the
      generator on main (read from git) and by this one, with the game's
      options, are byte identical as JSON. Known answer: the same 400
      seeds with a Lab style's weights differ. */
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { encode, decode, FIELDS, SEED_MAX, ALPHABET, CODE_LENGTH } from '../../src/lab/code.js';
import { labSpec, tidySettings, generatorOptions } from '../../src/lab/lab.js';
import { generateTrack } from '../../src/tracks/generate.js';
import { LOOP } from '../../src/tune.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..', '..');
const reviewDir = path.join(root, 'review', 'retention');
const quick = process.argv.includes('--quick');
const out = { started: new Date().toISOString() };
let failed = 0;
function verdict(label, ok, detail) { console.log((ok ? 'PASS ' : 'FAIL ') + label + (detail ? ': ' + detail : '')); if (!ok) failed++; return ok; }

/* a small seeded rng for the probe's own choices */
let rs = 20261108;
const rnd = () => { rs = (Math.imul(rs, 1664525) + 1013904223) >>> 0; return rs / 4294967296; };
const pick = arr => arr[Math.floor(rnd() * arr.length)];
function randomSettings() {
  const s = {};
  for (const [name, , options] of FIELDS) s[name] = pick(options);
  return tidySettings(s);
}
function centreHash(t) {
  let h = 0x811c9dc5;
  const feed = str => { for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 0x01000193); } };
  feed(t.kind + '|' + t.length + '|');
  for (const c of t.centre) feed(c.x + ',' + c.y + ',' + c.z + ',' + c.heading + ',' + c.bank + ',' + c.width + ';');
  return (h >>> 0).toString(16);
}

/* ---- 1. round trips ---- */
{
  console.log('\n== 1. round trips');
  const N = quick ? 100 : 1000;
  let same = 0, trackSame = 0, bad = 0, worstMs = 0, fallbacks = 0;
  const byStyle = {}, byLength = {};
  const kaCases = [];
  const t0 = Date.now();
  for (let i = 0; i < N; i++) {
    const s = randomSettings(), seed = Math.floor(rnd() * (SEED_MAX + 1));
    const code = encode(s, seed);
    const d = decode(code);
    if (d.error || d.seed !== seed || JSON.stringify(d.settings) !== JSON.stringify(s)) { bad++; continue; }
    same++;
    const a = labSpec(s, seed), b = labSpec(d.settings, d.seed);
    const t1 = performance.now();
    const ta = generateTrack(a.seed, { kind: a.kind, difficulty: a.difficulty, length: a.length, ...a.options });
    worstMs = Math.max(worstMs, performance.now() - t1);
    const tb = generateTrack(b.seed, { kind: b.kind, difficulty: b.difficulty, length: b.length, ...b.options });
    if (centreHash(ta) === centreHash(tb) && a.code === b.code) trackSame++;
    if (ta.fallback) fallbacks++;
    const st = byStyle[s.style] = byStyle[s.style] || { n: 0, fallbacks: 0, corners: 0, hairpins: 0, sweepers: 0 };
    st.n++; if (ta.fallback) st.fallbacks++; st.corners += ta.corners.length; st.hairpins += ta.corners.filter(c => c.type === 'hairpin' || c.type === 'double').length; st.sweepers += ta.corners.filter(c => c.type === 'sweeper' || c.type === 'flow' || c.type === 'multi').length;
    const lk = s.kind + ' ' + s.length + (s.cross ? ' crossover' : '');
    const le = byLength[lk] = byLength[lk] || { n: 0, fallbacks: 0, metres: 0, bridges: 0 };
    le.n++; if (ta.fallback) le.fallbacks++; le.metres += ta.length; if (ta.bridges && ta.bridges.length) le.bridges++;
    /* the known answer on a sample: one character changed */
    if (i % Math.max(1, Math.floor(N / 50)) === 0) {
      const pos = Math.floor(rnd() * CODE_LENGTH);
      let ch = code[pos]; while (ch === code[pos]) ch = ALPHABET[Math.floor(rnd() * ALPHABET.length)];
      const tampered = code.slice(0, pos) + ch + code.slice(pos + 1);
      const dt = decode(tampered);
      kaCases.push({ code, tampered, rejected: !!dt.error, sameTrack: !dt.error && dt.seed === seed && JSON.stringify(dt.settings) === JSON.stringify(s) });
    }
  }
  for (const k of Object.keys(byStyle)) { const st = byStyle[k]; st.cornersPerTrack = +(st.corners / st.n).toFixed(1); st.hairpinShare = +(st.hairpins / st.corners).toFixed(2); st.sweeperShare = +(st.sweepers / st.corners).toFixed(2); }
  for (const k of Object.keys(byLength)) { const le = byLength[k]; le.meanMetres = Math.round(le.metres / le.n); }
  out.roundTrips = { n: N, settingsAndSeedSame: same, trackSame, bad, fallbacks, worstGenerateMs: +worstMs.toFixed(0), seconds: +((Date.now() - t0) / 1000).toFixed(0), byStyle, byLength, knownAnswer: { cases: kaCases.length, rejected: kaCases.filter(c => c.rejected).length, sameTrack: kaCases.filter(c => c.sameTrack).length } };
  verdict(N + ' random settings and seeds encode and decode to the same track', same === N && trackSame === N, same + ' same settings, ' + trackSame + ' same centre line, ' + fallbacks + ' fallback layouts, worst generate ' + out.roundTrips.worstGenerateMs + ' ms');
  verdict('known answer: one character changed never gives the same track', kaCases.length > 0 && out.roundTrips.knownAnswer.sameTrack === 0, out.roundTrips.knownAnswer.rejected + ' of ' + kaCases.length + ' rejected, the rest another track');
  console.log('  by style: ' + Object.keys(byStyle).map(k => k + ' ' + byStyle[k].cornersPerTrack + ' corners, hairpins ' + byStyle[k].hairpinShare + ', sweepers ' + byStyle[k].sweeperShare + ', fallbacks ' + byStyle[k].fallbacks).join('; '));
  console.log('  by length: ' + Object.keys(byLength).sort().map(k => k + ' ' + byLength[k].meanMetres + ' m, bridges ' + byLength[k].bridges + '/' + byLength[k].n + ', fallbacks ' + byLength[k].fallbacks).join('; '));
}

/* ---- 2. malformed codes ---- */
{
  console.log('\n== 2. malformed codes');
  const valid = encode(tidySettings({ kind: 'circuit', length: 'long', style: 'hairpins', bank: true, cross: true, theme: 'docks', time: 'night' }), 123456);
  const set = [];
  set.push('', ' ', '-', 'ABC', valid.slice(0, 11), valid + 'A', valid + valid, 'hello world!', '😀😀😀😀😀😀😀😀😀😀😀😀', null, undefined, 42, {}, [], '\u0000'.repeat(12), 'IIIIIIIIIIII', 'UUUUUUUUUUUU');
  for (let i = 0; i < CODE_LENGTH; i++) for (const ch of ALPHABET) if (ch !== valid[i]) set.push(valid.slice(0, i) + ch + valid.slice(i + 1));   // every single substitution
  for (let i = 0; i < 2000; i++) set.push(Array.from({ length: CODE_LENGTH }, () => ALPHABET[Math.floor(rnd() * ALPHABET.length)]).join(''));
  /* a crossover where one cannot be: the settings packed by hand around the check */
  let rejected = 0, accepted = 0, threw = 0, sameAsValid = 0;
  const reasons = {};
  const acceptedSamples = [];
  for (const c of set) {
    let d;
    try { d = decode(c); } catch (e) { threw++; continue; }
    if (d.error) { rejected++; reasons[d.error] = (reasons[d.error] || 0) + 1; }
    else { accepted++; if (d.code === valid) sameAsValid++; if (acceptedSamples.length < 5) acceptedSamples.push(c); }
  }
  const validOk = !decode(valid).error && !decode(valid.toLowerCase()).error && !decode(valid.slice(0, 4) + '-' + valid.slice(4, 8) + ' ' + valid.slice(8)).error;
  out.malformed = { set: set.length, rejected, accepted, threw, sameAsValid, reasons, acceptedSamples, validStillDecodes: validOk };
  verdict('every malformed code of the fuzzed set (' + set.length + ') is rejected with a reason and nothing throws', rejected === set.length && threw === 0 && validOk, Object.keys(reasons).map(r => reasons[r] + ' ' + r).join('; '));
}

/* ---- 3. the default generator unchanged ---- */
{
  console.log('\n== 3. the default generator against main');
  const N = quick ? 40 : 400;
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'gen-main-'));
  let base = 'origin/main';
  try { execFileSync('git', ['rev-parse', '--verify', 'origin/main'], { cwd: root, stdio: 'pipe' }); } catch (e) { base = 'main'; }
  const baseCommit = execFileSync('git', ['rev-parse', base], { cwd: root }).toString().trim();
  for (const f of ['generate.js', 'dmath.js', 'analyse.js']) fs.writeFileSync(path.join(tmp, f), execFileSync('git', ['show', base + ':crazygames/game/src/tracks/' + f], { cwd: root }));
  const old = await import(pathToFileURL(path.join(tmp, 'generate.js')).href);
  let same = 0, differ = 0, styledDiffer = 0, styledSame = 0;
  const sample = [];
  const t0 = Date.now();
  for (let i = 0; i < N; i++) {
    const seed = Math.floor(rnd() * 4294967296);
    const opts = { kind: i % 2 ? 'sprint' : 'circuit', difficulty: +(rnd()).toFixed(2), length: pick([undefined, 560, 760, 820, 900, 1000, 1100]) };
    const a = JSON.stringify(old.generateTrack(seed, opts)), b = JSON.stringify(generateTrack(seed, opts));
    if (a === b) same++; else { differ++; if (sample.length < 5) sample.push({ seed, opts }); }
    if (i < (quick ? 10 : 60)) {
      const styled = JSON.stringify(generateTrack(seed, { ...opts, weights: LOOP.LAB.STYLES.hairpins }));
      if (styled === b) styledSame++; else styledDiffer++;
    }
  }
  fs.rmSync(tmp, { recursive: true, force: true });
  out.generator = { base, baseCommit, n: N, identical: same, differ, differingSamples: sample, seconds: +((Date.now() - t0) / 1000).toFixed(0), knownAnswer: { weights: 'hairpins', compared: styledSame + styledDiffer, differ: styledDiffer, same: styledSame } };
  verdict('the generator without the new options is byte identical to main (' + baseCommit.slice(0, 7) + ') on ' + N + ' seeds', same === N, same + ' identical, ' + differ + ' differ');
  verdict('known answer: the hairpins style\'s weights change the track', styledDiffer > 0 && styledSame <= 1, styledDiffer + ' of ' + (styledSame + styledDiffer) + ' differ');
}

fs.mkdirSync(reviewDir, { recursive: true });
fs.writeFileSync(path.join(reviewDir, 'codes.json'), JSON.stringify(out, null, 1));
console.log('\n' + (failed ? failed + ' FAILED' : 'all passed') + '; wrote review/retention/codes.json');
process.exit(failed ? 1 : 0);
